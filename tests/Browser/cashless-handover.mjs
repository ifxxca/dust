import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(path.resolve('workers/jne-report/package.json'));
const { chromium } = require('playwright');
const base = process.env.UI_UX_BASE_URL;
const output = process.env.CASHLESS_QA_OUTPUT;
assert(base && ['127.0.0.1', 'localhost'].includes(new URL(base).hostname));
assert(new URL(base).port === '8019', 'Use only the isolated QA server.');
assert(output);
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, colorScheme: 'light' });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(base + '/login');
    await page.locator('#email').fill('audit-pickup_staff@example.test');
    await page.locator('#password').fill('password');
    await page.locator('button[type="submit"]').click();
    await page.waitForURL((url) => !url.pathname.startsWith('/login'));
    assert.equal(await page.getByRole('link', { name: 'Handover Cashless', exact: true }).count(), 0);
    await page.goto(base + '/handover-cashless');
    await page.getByRole('heading', { name: 'Handover Cashless', exact: true }).waitFor();
    const requests = [];
    page.on('request', (request) => {
        if (new URL(request.url()).pathname.startsWith('/handover-cashless')) requests.push(request);
    });
    await page.getByLabel('Customer atau kode pickup').fill('AUD-PICKUP-0033');
    assert.equal(requests.length, 0, 'Typing does not search per character.');
    await page.getByRole('button', { name: 'Cari buku pickup', exact: true }).click();
    await page.getByRole('button', { name: /AUD-PICKUP-0033/ }).click();
    const scan = page.getByLabel('Scan atau ketik nomor resi');
    await scan.waitFor();
    await page.getByRole('radio', { name: 'PM', exact: true }).click();
    const savedBefore = Number((await page.getByText(/Resi tersimpan \(/).innerText()).match(/\((\d+)\)/)[1]);
    const savedLabel = `Resi tersimpan (${savedBefore + 3})`;
    const prefix = `TGQA${Date.now()}`;
    await scan.fill(prefix + '1');
    await scan.press('Enter');
    await page.getByText(prefix + '1', { exact: true }).waitFor();
    assert.equal(await scan.inputValue(), '');
    await scan.fill(prefix + '1');
    await scan.press('Enter');
    await page.getByText(`Resi ${prefix}1 sudah ada pada buku atau daftar ini.`, { exact: true }).waitFor();
    await scan.fill(prefix + '2');
    await page.getByRole('button', { name: 'Tambah', exact: true }).click();
    await page.getByRole('button', { name: `Keluarkan ${prefix}2 dari daftar`, exact: true }).click();
    assert.equal(await page.getByText(prefix + '2', { exact: true }).count(), 0);
    await scan.fill(prefix + '2');
    await scan.press('Enter');
    assert.equal(requests.filter((request) => request.method() === 'POST').length, 0, 'Scanning and removal only stage local data.');
    await page.screenshot({ path: path.join(output, 'desktop-staged.png'), fullPage: true });
    await scan.fill(prefix + '3');
    await page.getByRole('button', { name: 'Simpan Handover Cashless', exact: true }).click();
    await page.getByText(savedLabel, { exact: true }).waitFor();
    assert.equal(requests.filter((request) => request.method() === 'POST').length, 1, 'All three AWBs are saved in one request.');
    assert.equal(await page.getByRole('button', { name: /Keluarkan .* dari daftar/ }).count(), 0);
    await page.reload();
    await page.getByText(savedLabel, { exact: true }).waitFor();
    for (const number of ['1', '2', '3']) await page.getByText(prefix + number, { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'desktop-saved.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await scan.waitFor({ state: 'visible' });
    const rectangle = await scan.boundingBox();
    assert(rectangle && rectangle.y < 700, 'Mobile scan input remains near the top after selection.');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No horizontal page overflow on mobile.');
    await page.screenshot({ path: path.join(output, 'mobile-saved.png'), fullPage: true });
    await scan.fill(prefix + '4');
    await scan.press('Enter');
    await page.setViewportSize({ width: 1440, height: 1050 });
    page.once('dialog', (dialog) => dialog.dismiss());
    await page.getByRole('link', { name: 'Tugas Saya', exact: true }).click();
    assert(new URL(page.url()).pathname === '/handover-cashless', 'Unsaved scans prevent accidental navigation.');
    await page.getByText(prefix + '4', { exact: true }).waitFor();
    await page.getByRole('button', { name: `Keluarkan ${prefix}4 dari daftar`, exact: true }).click();
    await page.getByRole('button', { name: /AUD-PICKUP-0032/ }).click();
    await page.getByRole('heading', { name: 'Customer Audit 5', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'desktop-module.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ result: 'passed', flow: 'pickup selection, scanner Enter, manual entry, duplicate rejection, staged removal, one batch save, persistence, mobile, unsaved navigation guard', saved: 3, screenshots: output }));
} finally {
    await browser.close();
}
